"""Terraria game type (official dedicated server, native Linux).

Not a Steam download: Re-Logic publishes the server as a zip on terraria.org.
One shared install; each server has its own folder (settings file + worlds).
Setting names are serverconfig.txt keys. Admin commands go to the server's
console; who is online is read from its output.
"""
from __future__ import annotations

import io
import json
import os
import re
import shutil
import urllib.request
import zipfile

import config
import monitor
from games import common
from games.base import ActionError, GameType, opt_bool, opt_choice, opt_int, safe_name

NAMES_URL = "https://terraria.org/api/get/dedicated-servers-names"
ZIP_URL = "https://terraria.org/api/download/pc-dedicated-server/"
EXE = "TerrariaServer.bin.x86_64"
SIZES = [["1", "Small"], ["2", "Medium"], ["3", "Large"]]
DIFFICULTIES = [["0", "Classic"], ["1", "Expert"], ["2", "Master"], ["3", "Journey"]]
_EVENTS = re.compile(r"^(?P<joined>[^\r\n]{1,40}?) has joined\.\s*$|^(?P<left>[^\r\n]{1,40}?) has left\.\s*$", re.M)
_UA = {"User-Agent": "Mozilla/5.0 (GameDash)"}   # terraria.org refuses the default Python agent

_RUN_TEMPLATE = """#!/bin/bash
# gamedash-managed Terraria server — generated by provision().
# Settings: {server_dir}/serverconfig.txt
. {secrets}
# keep the join password in step with the ones set in GameDash
python3 - "{server_dir}/serverconfig.txt" "$GAME_SERVER_PASSWORD" <<'SYNC'
import re, sys
p, pw = sys.argv[1], sys.argv[2]
t = open(p, encoding="utf-8").read()
t = re.sub(r"(?m)^password=.*$", lambda m: "password=" + pw, t)
open(p, "w", encoding="utf-8").write(t)
SYNC
{console}cd "{install}" || exit 1
# The server's console is fed from the file above, so the dashboard can type
# commands into it (save, say, exit).
exec ./{exe} -config "{server_dir}/serverconfig.txt" > "{log}" 2>&1 < <(tail -n0 -F "$CONSOLE")
"""


class TerrariaGame(GameType):
    kind = "terraria"
    label = "Terraria"
    survives_connect_test = False   # connecting and hanging up crashes its server
    install_marker = EXE
    install_gb = 0.2
    ram_note = "about 1-2 GB of memory"
    about = "2D adventure and building. Very light on resources."
    actions = {"save", "broadcast", "kick", "ban"}

    provisionable = True
    port_layout = [
        {"name": "game", "klass": "game", "start": 7790, "proto": "TCP", "forward": True,
         "label": "Game port (TCP)", "help": "The port players connect to. Forward it (TCP)."},
    ]
    extra_fields = [
        {"name": "size", "label": "World size", "type": "select", "options": SIZES, "default": "2"},
        {"name": "difficulty", "label": "Difficulty", "type": "select", "options": DIFFICULTIES,
         "default": "0"},
        {"name": "maxplayers", "label": "Max players (1-255)", "type": "number", "min": 1, "max": 255,
         "default": 8},
        {"name": "seed", "label": "World seed — optional", "placeholder": "leave blank for a random world"},
        {"name": "motd", "label": "Welcome message — optional", "placeholder": ""},
        {"name": "secure", "label": "Extra cheat protection", "type": "checkbox", "default": True},
    ]
    provision_hint = ("Terraria — a new world in its own folder, created the first time the server "
                      "starts (a large world takes a minute or two). The join password is the shared one.")

    def install(self, install_dir: str, on_progress=None) -> tuple[bool, str]:
        try:
            req = urllib.request.Request(NAMES_URL, headers=_UA)
            with urllib.request.urlopen(req, timeout=30) as r:
                name = json.load(r)[0]
            if not re.match(r"^terraria-server-\d+\.zip$", name):
                return False, "terraria.org returned an unexpected file name"
            buf = io.BytesIO()
            with urllib.request.urlopen(urllib.request.Request(ZIP_URL + name, headers=_UA), timeout=60) as r:
                total = int(r.headers.get("Content-Length") or 0)
                while True:
                    chunk = r.read(1 << 16)
                    if not chunk:
                        break
                    buf.write(chunk)
                    if on_progress and total:
                        on_progress("downloading", 100.0 * buf.tell() / total)
            os.makedirs(install_dir, exist_ok=True)
            with zipfile.ZipFile(buf) as z:   # keep only the Linux build, flattened into install_dir
                for info in z.infolist():
                    parts = info.filename.split("/")
                    if len(parts) < 3 or parts[1] != "Linux" or info.is_dir():
                        continue
                    rel = os.path.normpath("/".join(parts[2:]))
                    if rel.startswith("..") or os.path.isabs(rel):
                        continue
                    dst = os.path.join(install_dir, rel)
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    with z.open(info) as src, open(dst, "wb") as out:
                        shutil.copyfileobj(src, out)
            os.chmod(os.path.join(install_dir, EXE), 0o755)
            with open(os.path.join(install_dir, "version.txt"), "w", encoding="utf-8") as f:
                f.write(name + "\n")
            return True, name
        except Exception as e:
            return False, f"couldn't download the Terraria server from terraria.org: {e}"

    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        if not os.path.isfile(os.path.join(install, EXE)):
            raise ActionError(f"Terraria isn't installed ({install}).")
        key = spec["key"]
        server_dir = os.path.join(install, "servers", key)
        if os.path.exists(os.path.join(server_dir, "serverconfig.txt")):
            raise ActionError(f"A Terraria server folder for this key already exists ({server_dir}).")
        display = safe_name((spec.get("name") or key).strip()) or key
        world = re.sub(r"[^A-Za-z0-9_]", "_", display)[:40] or "world"
        seed = (spec.get("seed") or "").strip()
        if not re.match(r"^[\w \-.]{0,40}$", seed):
            raise ActionError("World seed: letters, digits, spaces, . - and _ only (up to 40).")
        os.makedirs(os.path.join(server_dir, "worlds"), exist_ok=True)
        cfg = {
            "world": os.path.join(server_dir, "worlds", world + ".wld"),
            "worldpath": os.path.join(server_dir, "worlds"),
            "autocreate": opt_choice(spec, "size", [v for v, _ in SIZES], "2", "World size"),
            "worldname": world,
            "difficulty": opt_choice(spec, "difficulty", [v for v, _ in DIFFICULTIES], "0", "Difficulty"),
            "maxplayers": opt_int(spec, "maxplayers", 8, 1, 255, "Max players"),
            "port": ports["game"],
            "password": "set-at-launch",
            "motd": safe_name(spec.get("motd") or "", 120),
            "secure": "1" if opt_bool(spec, "secure", True) else "0",
            "upnp": "0",
            # each server keeps its own ban list (the default is one file shared by every server)
            "banlist": os.path.join(server_dir, "banlist.txt"),
        }
        if seed:
            cfg["seed"] = seed
        path = os.path.join(server_dir, "serverconfig.txt")
        common.write_private(path, "".join(f"{k}={v}\n" for k, v in cfg.items()))   # will hold the join password
        log = os.path.join(server_dir, "server.log")
        console = common.console_file(log)
        proc = f"-config {server_dir}/serverconfig.txt"
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(secrets=config.secrets_path(), server_dir=server_dir,
                                         install=install, exe=EXE, log=log,
                                         console=common.console_pipe_lines(console)))
        os.chmod(run, 0o755)
        stop = os.path.join(install, f"gamedash-{key}-stop.sh")
        common.stop_script(stop, console, "exit", proc)   # "exit" = save the world, then quit
        return {
            "exec_start": run, "exec_stop": stop, "working_dir": install,
            "game_port": ports["game"], "query_port": None, "rcon_port": None,
            "a2s": False, "proc_match": proc,
            "server_name": display, "join_port": ports["game"], "log_path": log,
            "install_dir": install, "timeout_stop": 60,
            "world": world, "save_root": server_dir,
        }

    def probe(self, s) -> dict:
        out = {"players": None, "player_names": [], "player_detail": [],
               "max_players": None, "reachable": monitor.port_listening(s.game_port)}
        names = monitor.roster_from_log(s.log_path, _EVENTS) if s.log_path else None
        if names is not None:
            out.update(players=len(names), player_names=names,
                       player_detail=[{"name": n, "id": n} for n in names])   # kicked/banned by name
        try:
            m = re.search(r"(?m)^maxplayers=(\d+)", open(os.path.join(s.save_root, "serverconfig.txt"),
                                                         encoding="utf-8").read())
            out["max_players"] = int(m.group(1)) if m else None
        except OSError:
            pass
        return out

    def valid_target(self, target: str) -> bool:
        return bool(re.match(r"^[^\r\n\x00-\x1f]{1,20}$", target))

    def _say(self, s, line: str, what: str) -> str:
        if not common.console_send(s, line):
            raise ActionError(f"{what} on {s.name} failed — the server's console isn't available.")
        return "sent"

    def save(self, s) -> str:
        return self._say(s, "save", "Save")

    def broadcast(self, s, message: str) -> str:
        return self._say(s, "say " + message[:200], "Message")

    def kick(self, s, target: str) -> str:
        return self._say(s, "kick " + target, "Kick")

    def ban(self, s, target: str) -> str:
        return self._say(s, "ban " + target, "Ban")
