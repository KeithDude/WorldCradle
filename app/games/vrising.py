"""V Rising game type. The dedicated server is Windows-only and runs under Wine.

Each server keeps its settings and saves in its own data folder (the launcher's
-persistentDataPath). Setting names are keys of ServerHostSettings.json; the
file is copied from the one shipped with the installed version so every other
default is right. Player numbers come from the Steam query port; messages go
through the game's RCON console.
"""
from __future__ import annotations

import json
import os

import config
import monitor
from games import common
from games.base import ActionError, GameType, opt_bool, opt_choice, opt_int, safe_name

EXE = "VRisingServer.exe"
_SETTINGS = "VRisingServer_Data/StreamingAssets/Settings"
PRESETS = [["StandardPvE", "Standard PvE (players vs the world)"], ["StandardPvP", "Standard PvP"],
           ["HardcorePvP", "Hardcore PvP (full loot)"], ["DuoPvP", "Duo PvP (clans of two)"],
           ["SoloPvP", "Solo PvP"]]

_RUN_TEMPLATE = """#!/bin/sh
# gamedash-managed V Rising server — generated by provision().
# Settings: {data_dir}/Settings/ServerHostSettings.json (and ServerGameSettings.json)
. {secrets}
# keep the join + admin-console passwords in step with the central registry
python3 - "{data_dir}/Settings/ServerHostSettings.json" "$GAME_SERVER_PASSWORD" "$GAME_ADMIN_PASSWORD" <<'SYNC'
import json, sys
p, join, admin = sys.argv[1:4]
d = json.load(open(p, encoding="utf-8-sig"))
d["Password"] = join
d.setdefault("Rcon", {{}})["Password"] = admin
json.dump(d, open(p, "w", encoding="utf-8"), indent=2)
SYNC
{wine}cd "{install}" || exit 1
# The server refuses to start without a display ("Failed to create batch mode
# window"), so it gets an invisible virtual one.
exec xvfb-run -a -s "-screen 0 640x480x24 -nolisten tcp" wine ./{exe} -persistentDataPath "{data_dir_win}" -logFile "{log_win}"
"""


def _win(path: str) -> str:
    """A Linux path as Wine sees it (drive Z: is the whole filesystem)."""
    return "Z:" + path.replace("/", "\\\\")


class VRisingGame(GameType):
    kind = "vrising"
    label = "V Rising"
    steam_app = 1829350
    steam_platform = "windows"
    requires = ["wine", "xvfb-run"]
    install_marker = EXE
    install_gb = 2
    ram_note = "about 4-8 GB of memory"
    about = "Vampire survival and castle building. The server is Windows-only, so it runs through Wine."
    actions = {"broadcast"}

    provisionable = True
    base_port = 9876
    port_layout = [
        {"name": "game", "klass": "game", "start": 9876, "proto": "UDP", "forward": True,
         "label": "Game port (UDP)", "help": "The port players connect to. Forward it (UDP)."},
        {"name": "query", "klass": "query", "start": 9877, "proto": "UDP", "forward": True,
         "label": "Steam query port (UDP)", "help": "Lists the server in the browser. Forward it (UDP)."},
        {"name": "rcon", "klass": "rcon", "start": 25600, "proto": "TCP", "label": "Admin console port (TCP)",
         "help": "Lets the dashboard control the server (player list, messages, saving). Keep it closed: never forward it on your router — anyone who could reach it could take over the server."},
    ]
    extra_fields = [
        {"name": "preset", "label": "Rules", "type": "select", "options": PRESETS, "default": "StandardPvE"},
        {"name": "maxplayers", "label": "Max players (1-128)", "type": "number", "min": 1, "max": 128,
         "default": 10},
        {"name": "description", "label": "Description shown in the server list — optional", "placeholder": ""},
        {"name": "listed", "label": "List in the public server browser", "type": "checkbox", "default": True,
         "help": "When this is off the server doesn't answer Steam's query either, so the dashboard "
                 "can't show how many players are on."},
    ]
    provision_hint = ("V Rising — a new world in its own folder (a Windows server, run through Wine). The "
                      "join password is the shared one. The detailed rules start from the chosen preset "
                      "and live in the server's ServerGameSettings.json. Its first start takes a minute "
                      "longer while its Wine environment (about 1 GB) is created.")

    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        template = os.path.join(install, _SETTINGS)
        if not (os.path.isfile(os.path.join(install, EXE)) and os.path.isdir(template)):
            raise ActionError(f"V Rising isn't installed ({install}).")
        key = spec["key"]
        data_dir = os.path.join(install, "gamedash-servers", key)
        settings_dir = os.path.join(data_dir, "Settings")
        if os.path.exists(os.path.join(settings_dir, "ServerHostSettings.json")):
            raise ActionError(f"A V Rising server folder for this key already exists ({data_dir}).")
        display = safe_name((spec.get("name") or key).strip()) or key
        preset = opt_choice(spec, "preset", [p for p, _ in PRESETS], "StandardPvE", "Rules")
        if not os.path.isfile(os.path.join(install, "VRisingServer_Data/StreamingAssets/GameSettingPresets",
                                           preset + ".json")):
            raise ActionError(f"This version of V Rising doesn't have the “{preset}” rules.")
        listed = opt_bool(spec, "listed", True)
        host = json.load(open(os.path.join(template, "ServerHostSettings.json"), encoding="utf-8-sig"))
        host.update({
            "Name": display, "Description": safe_name(spec.get("description") or "", 200),
            "Port": ports["game"], "QueryPort": ports["query"],
            "MaxConnectedUsers": opt_int(spec, "maxplayers", 10, 1, 128, "Max players"),
            "SaveName": "world", "Password": "set-at-launch",
            "ListOnSteam": listed, "ListOnEOS": listed,
            "GameSettingsPreset": preset,
            "Rcon": {"Enabled": True, "Port": ports["rcon"], "Password": "set-at-launch"},
        })
        os.makedirs(settings_dir, exist_ok=True)
        fd = os.open(os.path.join(settings_dir, "ServerHostSettings.json"),
                     os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)   # will hold both passwords
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(host, f, indent=2)
        log = os.path.join(data_dir, "VRisingServer.log")
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(
                secrets=config.secrets_path(), install=install, exe=EXE, data_dir=data_dir,
                data_dir_win=_win(data_dir), log_win=_win(log),
                wine=common.wine_env_lines(common.wine_prefix(self.kind, key))))
        os.chmod(run, 0o755)
        return {
            "exec_start": run, "working_dir": install,
            "game_port": ports["game"], "query_port": ports["query"], "rcon_port": ports["rcon"],
            "rcon_password_ref": "GAME_ADMIN_PASSWORD",
            "a2s": True, "proc_match": f"gamedash-servers\\\\{key}",
            "server_name": display, "join_port": ports["game"], "log_path": log,
            "install_dir": install, "steam_app": self.steam_app,
            # no graceful shutdown under Wine — the game autosaves every two minutes
            "kill_signal": "SIGINT", "timeout_stop": 30,
            "world": key, "save_root": os.path.join(data_dir, "Saves"),
        }

    def save_paths(self, s) -> list[dict]:
        return [{"path": s.save_root, "role": "save"}] if s.save_root else []

    def probe(self, s) -> dict:
        out = {"players": None, "player_names": [], "player_detail": [],
               "max_players": None, "reachable": None}
        info = monitor.a2s_info(s.query_port) if s.query_port else None
        if info is not None:
            names = monitor.a2s_player_names(s.query_port) if info["players"] else []
            out.update(reachable=True, players=info["players"], max_players=info["max_players"],
                       player_names=names, player_detail=[{"name": n, "id": ""} for n in names])
        return out

    def broadcast(self, s, message: str) -> str:
        r = monitor.rcon_run(s.rcon_port, s.rcon_password, "announce " + message.replace("\n", " ")[:200])
        if r is None:
            raise ActionError(f"Message to {s.name} failed (the admin console didn't answer).")
        return "sent"
