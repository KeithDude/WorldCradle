"""Necesse game type (native Linux dedicated server; ships its own Java).

Everything is a launch argument; each server keeps its world, settings and
logs in its own data folder (-datadir). Admin commands go to the server's
console; who is online is read from its output.
"""
from __future__ import annotations

import os
import re

import config
import monitor
from games import common
from games.base import ActionError, GameType, opt_bool, opt_int, safe_name

MARKER = "Server.jar"
_EVENTS = re.compile(r'Player \d+ \("(?P<joined>[^"\r\n]+)"\) connected|Player \d+ \("(?P<left>[^"\r\n]+)"\) disconnected')

_RUN_TEMPLATE = """#!/bin/bash
# gamedash-managed Necesse server — generated by provision().
# World, settings and logs: {server_dir}
. {secrets}
{console}cd "{install}" || exit 1
# The server's console is fed from the file above, so the dashboard can type
# commands into it (save, say, stop).
exec ./jre/bin/java -XX:+UseG1GC -XX:MaxGCPauseMillis=50 -jar Server.jar -nogui \\
    -datadir "{server_dir}" -world "{world}" -port {gp} -slots {maxp} \\
    -password "$GAME_SERVER_PASSWORD" -pausewhenempty {pause} -logging 1 \\
    > "{log}" 2>&1 < <(tail -n0 -F "$CONSOLE")
"""


class NecesseGame(GameType):
    kind = "necesse"
    label = "Necesse"
    steam_app = 1169370
    install_marker = MARKER
    install_gb = 0.4
    ram_note = "about 1-2 GB of memory"
    about = "Top-down sandbox adventure with settlements. Very light on resources."
    actions = {"save", "broadcast", "kick", "ban"}

    provisionable = True
    base_port = 14159
    port_layout = [
        {"name": "game", "klass": "game", "start": 14159, "proto": "UDP", "forward": True,
         "label": "Game port (UDP)", "help": "The port players connect to. Forward it (UDP)."},
    ]
    extra_fields = [
        {"name": "maxplayers", "label": "Max players (1-250)", "type": "number", "min": 1, "max": 250,
         "default": 10},
        {"name": "pause_empty", "label": "Pause the world when nobody is online", "type": "checkbox",
         "default": True},
    ]
    provision_hint = ("Necesse — a new world in its own folder, created the first time the server "
                      "starts. The join password is the shared one.")

    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        if not os.path.isfile(os.path.join(install, MARKER)):
            raise ActionError(f"Necesse isn't installed ({install}).")
        key = spec["key"]
        server_dir = os.path.join(install, "gamedash-servers", key)
        if os.path.isdir(server_dir):
            raise ActionError(f"A Necesse server folder for this key already exists ({server_dir}).")
        display = safe_name((spec.get("name") or key).strip()) or key
        world = re.sub(r"[^A-Za-z0-9_]", "_", key)
        os.makedirs(server_dir, exist_ok=True)
        log = os.path.join(server_dir, "gamedash-console.log")
        console = common.console_file(log)
        proc = f"-datadir {server_dir}"
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(
                secrets=config.secrets_path(), install=install, server_dir=server_dir, world=world,
                gp=ports["game"], maxp=opt_int(spec, "maxplayers", 10, 1, 250, "Max players"),
                pause="1" if opt_bool(spec, "pause_empty", True) else "0", log=log,
                console=common.console_pipe_lines(console)))
        os.chmod(run, 0o755)
        stop = os.path.join(install, f"gamedash-{key}-stop.sh")
        common.stop_script(stop, console, "stop", proc)   # saves, then quits
        return {
            "exec_start": run, "exec_stop": stop, "working_dir": install,
            "game_port": ports["game"], "query_port": None, "rcon_port": None,
            "a2s": False, "proc_match": proc,
            "server_name": display, "join_port": ports["game"], "log_path": log,
            "install_dir": install, "steam_app": self.steam_app, "timeout_stop": 60,
            "world": world, "save_root": server_dir,
        }

    def save_paths(self, s) -> list[dict]:
        return [{"path": s.save_root, "role": "save"}] if s.save_root else []

    def probe(self, s) -> dict:
        out = {"players": None, "player_names": [], "player_detail": [],
               "max_players": None, "reachable": None}
        names = monitor.roster_from_log(s.log_path, _EVENTS) if s.log_path else None
        if names is not None:
            out.update(players=len(names), player_names=names,
                       player_detail=[{"name": n, "id": n} for n in names])
        try:   # the startup line states the player limit
            with open(s.log_path, encoding="utf-8", errors="replace") as f:
                m = re.search(r"with (\d+) slots", f.read(8192))
            out["max_players"] = int(m.group(1)) if m else None
        except OSError:
            pass
        return out

    def valid_target(self, target: str) -> bool:
        return bool(re.match(r'^[^\r\n"\x00-\x1f]{1,40}$', target))

    def _type(self, s, line: str, what: str) -> str:
        if not common.console_send(s, line):
            raise ActionError(f"{what} on {s.name} failed — the server's console isn't available.")
        return "sent"

    def save(self, s) -> str:
        return self._type(s, "save", "Save")

    def broadcast(self, s, message: str) -> str:
        return self._type(s, "say " + message[:200], "Message")

    def kick(self, s, target: str) -> str:
        return self._type(s, f'kick "{target}"', "Kick")

    def ban(self, s, target: str) -> str:
        return self._type(s, f'ban "{target}"', "Ban")
