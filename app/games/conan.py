"""Conan Exiles game type. The dedicated server runs under Wine (Windows build).

Each server keeps its settings, database and logs in its own folder (the
server's -userdir option). Setting names are keys of the game's ini files.
Players and messages go through the game's RCON console.
"""
from __future__ import annotations

import os
import re

import config
import monitor
from games import common
from games.base import ActionError, GameType, opt_choice, opt_int, safe_name
from games.simple import RCON_PORT_HELP

EXE = "ConanSandbox/Binaries/Win64/ConanSandboxServer-Win64-Shipping.exe"
_CFG = "Saved/Config/WindowsServer"   # inside the server's own folder (-userdir)

_RUN_TEMPLATE = """#!/bin/sh
# gamedash-managed Conan Exiles server — generated by provision().
# Settings: {server_dir}/{cfg}/ServerSettings.ini (and Engine.ini, Game.ini)
. {secrets}
# keep the admin + admin-console passwords in step with the ones set in GameDash
python3 - "{server_dir}/{cfg}" "$GAME_ADMIN_PASSWORD" <<'SYNC'
import re, sys
d, admin = sys.argv[1], sys.argv[2]
for name, key in (("ServerSettings.ini", "AdminPassword"), ("Game.ini", "RconPassword")):
    p = d + "/" + name
    t = open(p, encoding="utf-8").read()
    t = re.sub(r"(?m)^%s=.*$" % key, lambda m: key + "=" + admin, t)
    open(p, "w", encoding="utf-8").write(t)
SYNC
{wine}cd "{install}/ConanSandbox/Binaries/Win64" || exit 1
exec wine ./ConanSandboxServer-Win64-Shipping.exe -log -userdir="{userdir_win}" \\
    -Port={gp} -QueryPort={qp} -MaxPlayers={maxp} \\
    -ServerName="{name}" -ServerPassword="$GAME_SERVER_PASSWORD"
"""


class ConanGame(GameType):
    kind = "conan"
    label = "Conan Exiles"
    steam_app = 443030
    steam_platform = "windows"
    requires = ["wine"]
    install_marker = EXE
    install_gb = 5
    ram_note = "about 6-10 GB of memory"
    about = "Open-world survival in the world of Conan. Runs through Wine."
    actions = {"broadcast"}

    provisionable = True
    port_layout = [
        {"name": "game", "klass": "game", "start": 7790, "span": 2, "proto": "UDP", "forward": True,
         "label": "Game port (UDP)", "help": "The game also uses the next port up. Forward both (UDP)."},
        {"name": "query", "klass": "query", "start": 27080, "proto": "UDP", "forward": True,
         "label": "Steam query port (UDP)", "help": "Lists the server in the browser. Forward it (UDP)."},
        {"name": "rcon", "klass": "rcon", "start": 25620, "proto": "TCP", "label": "Admin console port (TCP)",
         "help": RCON_PORT_HELP},
    ]
    extra_fields = [
        {"name": "maxplayers", "label": "Max players (1-70)", "type": "number", "min": 1, "max": 70,
         "default": 10},
        {"name": "mode", "label": "Combat", "type": "select", "default": "pve",
         "options": [["pve", "PvE (players vs the world)"], ["pvp", "PvP (players can fight and raid)"]]},
    ]
    provision_hint = ("Conan Exiles — a new world in its own folder (run through Wine). The join password "
                      "is the shared one; the shared admin password unlocks the in-game admin panel. "
                      "Rates and rules start at the game's defaults and can be changed in-game as admin. "
                      "Its first start takes a few minutes.")

    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        if not os.path.isfile(os.path.join(install, EXE)):
            raise ActionError(f"Conan Exiles isn't installed ({install}).")
        key = spec["key"]
        server_dir = os.path.join(install, "gamedash-servers", key)
        cfg_dir = os.path.join(server_dir, _CFG)
        if os.path.isdir(cfg_dir):
            raise ActionError(f"A Conan Exiles server folder for this key already exists ({server_dir}).")
        display = safe_name((spec.get("name") or key).strip()) or key
        pvp = opt_choice(spec, "mode", ["pve", "pvp"], "pve", "Combat") == "pvp"
        os.makedirs(cfg_dir, exist_ok=True)
        # the server adds every other setting, with its default, on first start
        for name, body in (
            ("ServerSettings.ini", f"[ServerSettings]\nPVPEnabled={'True' if pvp else 'False'}\n"
                                   "AdminPassword=set-at-launch\n"),
            ("Game.ini", f"[RconPlugin]\nRconEnabled=1\nRconPort={ports['rcon']}\n"
                         "RconPassword=set-at-launch\nRconMaxKarma=60\n"),
        ):
            common.write_private(os.path.join(cfg_dir, name), body)
        prefix = common.wine_prefix(self.kind, key)
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(
                secrets=config.secrets_path(), install=install, server_dir=server_dir, cfg=_CFG,
                userdir_win="Z:" + server_dir.replace("/", "\\\\") + "\\\\",
                gp=ports["game"], qp=ports["query"], rp=ports["rcon"], name=display,
                maxp=opt_int(spec, "maxplayers", 10, 1, 70, "Max players"),
                wine=common.wine_env_lines(prefix)))
        os.chmod(run, 0o755)
        return {
            "exec_start": run, "working_dir": install,
            "game_port": ports["game"], "query_port": ports["query"], "rcon_port": ports["rcon"],
            "rcon_password_ref": "GAME_ADMIN_PASSWORD",
            "a2s": True, "proc_match": f"gamedash-servers\\\\{key}\\\\",
            "server_name": display, "join_port": ports["game"],
            "log_path": os.path.join(server_dir, "Saved/Logs/ConanSandbox.log"),
            "install_dir": install, "steam_app": self.steam_app,
            # no graceful shutdown under Wine — the game saves to its database continuously
            "kill_signal": "SIGINT", "timeout_stop": 30,
            "world": key, "save_root": os.path.join(server_dir, "Saved"),
        }

    @staticmethod
    def parse_players(text: str) -> list[str] | None:
        # header row, then "  0 | CharName | PlayerName | UserID | PlatformID | PlatformName"
        if "Idx" not in (text or ""):
            return None
        names = []
        for line in text.splitlines()[1:]:
            cols = [c.strip() for c in line.split("|")]
            if len(cols) >= 3 and cols[0].isdigit():
                names.append(cols[1] or cols[2])
        return names

    # The game's RCON replies don't follow the protocol strictly, so it is read
    # with the tolerant client (monitor.palworld_rcon), like Palworld's.
    def probe(self, s) -> dict:
        out = {"players": None, "player_names": [], "player_detail": [],
               "max_players": None, "reachable": None}
        info = monitor.a2s_info(s.query_port) if s.query_port else None
        if info is not None:
            out.update(reachable=True, players=info["players"], max_players=info["max_players"])
        names = self.parse_players(monitor.palworld_rcon(s.rcon_port, s.rcon_password, "listplayers") or "") \
            if s.rcon_port else None
        if names is not None:
            out.update(reachable=True, players=len(names), player_names=names,
                       player_detail=[{"name": n, "id": ""} for n in names])
        return out

    def broadcast(self, s, message: str) -> str:
        r = monitor.palworld_rcon(s.rcon_port, s.rcon_password,
                             'broadcast "' + re.sub(r'["\r\n]', " ", message)[:200] + '"')
        if r is None:
            raise ActionError(f"Message to {s.name} failed (the admin console didn't answer).")
        return "sent"
