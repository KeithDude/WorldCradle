    # ---- install (not Steam: fetch the official jar from Mojang) -----------
    def install(self, install_dir: str, on_progress=None) -> tuple[bool, str]:
        try:
            with urllib.request.urlopen(MANIFEST_URL, timeout=30) as r:
                manifest = json.load(r)
            version = manifest["latest"]["release"]
            meta_url = next(v["url"] for v in manifest["versions"] if v["id"] == version)
            with urllib.request.urlopen(meta_url, timeout=30) as r:
                meta = json.load(r)
            need = (meta.get("javaVersion") or {}).get("majorVersion")
            have = _java_major()
            if need and have and have < need:
                return False, (f"Minecraft {version} needs Java {need} or newer, and this computer "
                               f"has Java {have}. Update Java, then try again.")
            dl = meta["downloads"]["server"]
            os.makedirs(install_dir, exist_ok=True)
            tmp = os.path.join(install_dir, "server.jar.part")
            sha, got = hashlib.sha1(), 0
            with urllib.request.urlopen(dl["url"], timeout=60) as r, open(tmp, "wb") as f:
                while True:
                    chunk = r.read(1 << 16)
                    if not chunk:
                        break
                    f.write(chunk)
                    sha.update(chunk)
                    got += len(chunk)
                    if on_progress:
                        on_progress("downloading", 100.0 * got / max(1, dl["size"]))
            if sha.hexdigest() != dl["sha1"]:   # never run a jar that isn't the one Mojang published
                os.unlink(tmp)
                return False, "the download was damaged (checksum mismatch) — please try again"
            os.replace(tmp, os.path.join(install_dir, "server.jar"))
            with open(os.path.join(install_dir, "version.txt"), "w", encoding="utf-8") as f:
                f.write(version + "\n")
            return True, f"Minecraft {version}"
        except Exception as e:
            return False, f"couldn't download the Minecraft server from Mojang: {e}"

    # ---- provisioning ------------------------------------------------------
    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        jar = os.path.join(install, "server.jar")
        if not os.path.isfile(jar):
            raise ActionError(f"Minecraft isn't installed ({jar} missing).")
        if not shutil.which("java"):
            raise ActionError("Java isn't installed on this computer — Minecraft needs it.")
        key = spec["key"]
        server_dir = os.path.join(install, "servers", key)
        if os.path.exists(os.path.join(server_dir, "server.properties")):
            raise ActionError(f"A Minecraft server folder for this key already exists ({server_dir}). "
                              f"Pick a different key, or move that folder away first.")
        display = safe_name((spec.get("name") or key).strip()) or key
        ram = opt_int(spec, "memory", 2, 1, 32, "Memory")
        names = [n.strip() for n in (spec.get("whitelist_names") or "").split(",") if n.strip()]
        bad = [n for n in names if not _NAME_RE.match(n)]
        if bad:
            raise ActionError(f"Not a valid Minecraft username: {bad[0]} (letters, digits and _ only, "
                              f"up to 16 characters).")
        seed = (spec.get("seed") or "").strip()
        if not re.match(r"^[\w \-]{0,64}$", seed):
            raise ActionError("World seed: letters, digits, spaces, - and _ only (up to 64).")
        b = lambda name, default: str(opt_bool(spec, name, default)).lower()  # noqa: E731
        whitelist = opt_bool(spec, "whitelist", True)
        props = {
            "motd": display,
            "server-port": ports["game"],
            "max-players": opt_int(spec, "maxplayers", 10, 1, 200, "Max players"),
            "gamemode": opt_choice(spec, "gamemode", [v for v, _ in GAMEMODES], "survival", "Game mode"),
            "difficulty": opt_choice(spec, "difficulty", [v for v, _ in DIFFICULTIES], "easy", "Difficulty"),
            "hardcore": b("hardcore", False),
            "white-list": str(whitelist).lower(), "enforce-whitelist": str(whitelist).lower(),
            "level-type": opt_choice(spec, "world_type", [v for v, _ in WORLD_TYPES],
                                     "minecraft:normal", "World type").replace(":", "\\:"),
            "level-seed": seed,
            "view-distance": opt_int(spec, "view_distance", 10, 3, 32, "View distance"),
            "online-mode": "true",          # verify accounts with Mojang (blocks impersonation)
            "enable-rcon": "true", "rcon.port": ports["rcon"],
            "rcon.password": "set-at-launch",   # the run script fills in the real one
            "enable-query": "false",
        }
        os.makedirs(server_dir, exist_ok=True)
        fd = os.open(os.path.join(server_dir, "server.properties"),
                     os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)   # will hold the RCON password
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write("".join(f"{k}={v}\n" for k, v in props.items()))
        with open(os.path.join(server_dir, "eula.txt"), "w", encoding="utf-8") as f:
            f.write(f"# Accepted in GameDash's Add-a-server form by the operator ({EULA_URL})\neula=true\n")
        # PvP and command blocks stopped being server.properties settings (Minecraft 1.21.9);
        # they are game rules now, set through the admin console once the server is up (see probe).
        with open(os.path.join(server_dir, "gamedash-gamerules.txt"), "w", encoding="utf-8") as f:
            f.write(f"gamerule pvp {b('pvp', True)}\n"
                    f"gamerule command_blocks_work {b('command_blocks', False)}\n")
        if names:  # added through the admin console once the server is up (see probe)
            with open(os.path.join(server_dir, "gamedash-whitelist.txt"), "w", encoding="utf-8") as f:
                f.write("\n".join(names) + "\n")
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(secrets=config.secrets_path(), server_dir=server_dir,
                                         jar=jar, ram=ram, key=key))
        os.chmod(run, 0o755)
        # the admin console's "stop" saves the world and exits cleanly
        stop = os.path.join(install, f"gamedash-{key}-stop.sh")
        common.rcon_stop_script(stop, config.secrets_path(), ports["rcon"], "stop", f"servers/{key}", wait=45)
        return {
            "exec_start": run, "exec_stop": stop, "working_dir": server_dir,
            "game_port": ports["game"], "query_port": None, "rcon_port": ports["rcon"],
            "rcon_password_ref": "GAME_ADMIN_PASSWORD",
            "a2s": False, "proc_match": f"servers/{key}",
            "server_name": display, "join_port": ports["game"],
            "log_path": os.path.join(server_dir, "logs", "latest.log"),
            "install_dir": install,
            "timeout_stop": 60,   # on stop the server saves the world before exiting
            "world": key, "save_root": server_dir,
        }

    def save_paths(self, s) -> list[dict]:
        return [{"path": s.save_root, "role": "save"}] if s.save_root else []

    # ---- monitoring + controls (RCON) --------------------------------------
    def _rcon(self, s, cmd: str) -> str | None:
        return monitor.rcon_run(s.rcon_port, s.rcon_password, cmd)

    def _apply_pending_whitelist(self, s) -> None:
        """First boot: add the names typed on the Add form, then forget the list."""
        path = os.path.join(s.save_root or "", "gamedash-whitelist.txt")
        if not s.save_root or not os.path.isfile(path):
            return
        names = [n.strip() for n in open(path, encoding="utf-8") if _NAME_RE.match(n.strip())]
        if all(self._rcon(s, f"whitelist add {n}") is not None for n in names):
            os.unlink(path)

    def _apply_pending_gamerules(self, s) -> None:
        """First boot: set the game rules chosen on the Add form, then forget the list."""
        path = os.path.join(s.save_root or "", "gamedash-gamerules.txt")
        if not s.save_root or not os.path.isfile(path):
            return
        lines = [l.strip() for l in open(path, encoding="utf-8")
                 if re.match(r"^gamerule [a-z_]+ (true|false)$", l.strip())]
        if all("is now set to" in (self._rcon(s, l) or "") for l in lines):
            os.unlink(path)

    @staticmethod
    def parse_list(text: str) -> tuple[int, int, list[str]] | None:
        m = _LIST_RE.search(re.sub(r"§.", "", text or ""))
        if not m:
            return None
        names = [n.strip() for n in m.group(3).split(",") if n.strip()]
        return int(m.group(1)), int(m.group(2)), names

    def probe(self, s) -> dict:
        out = {"players": None, "player_names": [], "player_detail": [],
               "max_players": None, "reachable": monitor.tcp_open(s.game_port)}
        parsed = self.parse_list(self._rcon(s, "list") or "")
        if parsed:
            count, limit, names = parsed
            out.update(players=count, max_players=limit, player_names=names,
                       # Minecraft kicks/bans by name, so the name doubles as the id
                       player_detail=[{"name": n, "id": n} for n in names])
            self._apply_pending_whitelist(s)
            self._apply_pending_gamerules(s)
        return out

    def valid_target(self, target: str) -> bool:
        return bool(_NAME_RE.match(target))

    def save(self, s) -> str:
        r = self._rcon(s, "save-all")
        if r is None:
            raise ActionError(f"Save on {s.name} failed (the admin console didn't answer).")
        return r.strip() or "saved"

    def broadcast(self, s, message: str) -> str:
        if self._rcon(s, "say " + message.replace("\n", " ")[:200]) is None:
            raise ActionError(f"Message to {s.name} failed (the admin console didn't answer).")
        return "sent"

    def kick(self, s, target: str) -> str:
        r = self._rcon(s, "kick " + target)
        if r is None:
            raise ActionError(f"Kick on {s.name} failed (the admin console didn't answer).")
        return r.strip() or "ok"

    def ban(self, s, target: str) -> str:
        r = self._rcon(s, "ban " + target)
        if r is None:
            raise ActionError(f"Ban on {s.name} failed (the admin console didn't answer).")
        return r.strip() or "ok"
