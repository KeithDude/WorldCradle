"""Icarus game type. The dedicated server is Windows-only and runs under Wine.

Each server keeps its settings and saves in its own folder (the server's
-UserDir option). Setting names are keys of ServerSettings.ini. Player numbers
come from the Steam query port; there is no remote console — admins use the
in-game chat commands after "/AdminLogin <admin password>".
"""
from __future__ import annotations

import os

import config
import monitor
from games import common
from games.base import ActionError, GameType, opt_bool, opt_int, safe_name

EXE = "Icarus/Binaries/Win64/IcarusServer-Win64-Shipping.exe"
_CFG = "Saved/Config/WindowsServer"

_RUN_TEMPLATE = """#!/bin/sh
# gamedash-managed Icarus server — generated by provision().
# Settings: {server_dir}/{cfg}/ServerSettings.ini
. {secrets}
# keep the join + admin passwords in step with the central registry
python3 - "{server_dir}/{cfg}/ServerSettings.ini" "$GAME_SERVER_PASSWORD" "$GAME_ADMIN_PASSWORD" <<'SYNC'
import re, sys
p, join, admin = sys.argv[1:4]
t = open(p, encoding="utf-8").read()
for key, val in (("JoinPassword", join), ("AdminPassword", admin)):
    t = re.sub(r"(?m)^%s=.*$" % key, lambda m: key + "=" + val, t)
open(p, "w", encoding="utf-8").write(t)
SYNC
{wine}cd "{install}/Icarus/Binaries/Win64" || exit 1
exec wine ./IcarusServer-Win64-Shipping.exe -Log -UserDir="{userdir_win}" \\
    -SteamServerName="{name}" -PORT={gp} -QueryPort={qp}
"""


class IcarusGame(GameType):
    kind = "icarus"
    label = "Icarus"
    steam_app = 2089300
    steam_platform = "windows"
    requires = ["wine"]
    install_marker = EXE
    install_gb = 10
    ram_note = "about 8-12 GB of memory"
    about = "Session-based survival on an alien planet, up to 8 players. Runs through Wine."
    actions: set[str] = set()

    provisionable = True
    base_port = 17777
    port_layout = [
        {"name": "game", "klass": "game", "start": 17777, "proto": "UDP", "forward": True,
         "label": "Game port (UDP)", "help": "The port players connect to. Forward it (UDP)."},
        {"name": "query", "klass": "query", "start": 27095, "proto": "UDP", "forward": True,
         "label": "Steam query port (UDP)", "help": "Lists the server in the browser. Forward it (UDP)."},
    ]
    extra_fields = [
        {"name": "maxplayers", "label": "Max players (1-8)", "type": "number", "min": 1, "max": 8,
         "default": 8},
        {"name": "anyone_launch", "label": "Any player may start a mission (off = admins only)",
         "type": "checkbox", "default": True},
        {"name": "anyone_delete", "label": "Any player may delete a mission's save",
         "type": "checkbox", "default": False},
    ]
    provision_hint = ("Icarus — a new server with its own save folder (a Windows server, run through "
                      "Wine). The join password is the shared one. After joining, type "
                      "/AdminLogin followed by the shared admin password in chat to manage it. The "
                      "first player to join picks the mission (“prospect”) or open world to play.")

    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        if not os.path.isfile(os.path.join(install, EXE)):
            raise ActionError(f"Icarus isn't installed ({install}).")
        key = spec["key"]
        server_dir = os.path.join(install, "gamedash-servers", key)
        cfg_dir = os.path.join(server_dir, _CFG)
        if os.path.isdir(cfg_dir):
            raise ActionError(f"An Icarus server folder for this key already exists ({server_dir}).")
        display = safe_name((spec.get("name") or key).strip()) or key
        b = lambda name, default: "True" if opt_bool(spec, name, default) else "False"  # noqa: E731
        ini = ("[/Script/Icarus.DedicatedServerSettings]\n"
               f"SessionName={display}\n"
               "JoinPassword=set-at-launch\n"
               f"MaxPlayers={opt_int(spec, 'maxplayers', 8, 1, 8, 'Max players')}\n"
               "AdminPassword=set-at-launch\n"
               # by default the server quits when nobody has joined or everyone has left
               "ShutdownIfNotJoinedFor=-1.000000\n"
               "ShutdownIfEmptyFor=-1.000000\n"
               f"AllowNonAdminsToLaunchProspects={b('anyone_launch', True)}\n"
               f"AllowNonAdminsToDeleteProspects={b('anyone_delete', False)}\n"
               "ResumeProspect=True\n")
        os.makedirs(cfg_dir, exist_ok=True)
        fd = os.open(os.path.join(cfg_dir, "ServerSettings.ini"), os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(ini)
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(
                secrets=config.secrets_path(), install=install, server_dir=server_dir, cfg=_CFG,
                userdir_win="Z:" + server_dir.replace("/", "\\\\") + "\\\\",
                gp=ports["game"], qp=ports["query"], name=display,
                wine=common.wine_env_lines(common.wine_prefix(self.kind, key))))
        os.chmod(run, 0o755)
        return {
            "exec_start": run, "working_dir": install,
            "game_port": ports["game"], "query_port": ports["query"], "rcon_port": None,
            "a2s": True, "proc_match": f"gamedash-servers\\\\{key}\\\\",
            "server_name": display, "join_port": ports["game"],
            "log_path": os.path.join(server_dir, "Saved/Logs/Icarus.log"),
            "install_dir": install, "steam_app": self.steam_app,
            # no graceful shutdown under Wine — the game saves the mission as it goes
            "kill_signal": "SIGINT", "timeout_stop": 30,
            "world": key, "save_root": os.path.join(server_dir, "Saved"),
        }

    def save_paths(self, s) -> list[dict]:
        return [{"path": s.save_root, "role": "save"}] if s.save_root else []

    def probe(self, s) -> dict:
        out = {"players": None, "player_names": [], "player_detail": [],
               "max_players": None, "reachable": None}
        info = monitor.a2s_info(s.query_port) if s.query_port else None
        if info is not None:
            names = monitor.a2s_player_names(s.query_port) if info["players"] else []
            out.update(reachable=True, players=info["players"], max_players=info["max_players"],
                       player_names=names, player_detail=[{"name": n, "id": ""} for n in names])
        return out
