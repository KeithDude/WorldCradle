    @staticmethod
    def _set(xml: str, name: str, value) -> str:
        # Some settings ship commented out (<!-- <property name="UserDataFolder" …/> -->); an
        # edit inside the comment would do nothing, so drop that line and add a live one.
        xml = re.sub(r'<!--\s*<property\s+name="%s"\s+value="[^"]*"\s*/>\s*-->' % re.escape(name), "", xml)
        pat = re.compile(r'(<property\s+name="%s"\s+value=)"[^"]*"' % re.escape(name))
        if not pat.search(xml):   # not in this version's file: add it rather than fail
            return xml.replace("</ServerSettings>",
                               f'\t<property name="{name}" value="{escape(str(value), {chr(34): "&quot;"})}"/>\n</ServerSettings>')
        return pat.sub(lambda m: m.group(1) + '"' + escape(str(value), {'"': "&quot;"}) + '"', xml)

    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        template = os.path.join(install, "serverconfig.xml")
        if not (os.path.isfile(os.path.join(install, EXE)) and os.path.isfile(template)):
            raise ActionError(f"7 Days to Die isn't installed ({install}).")
        key = spec["key"]
        server_dir = os.path.join(install, "worldcradle-servers", key)
        if os.path.exists(os.path.join(server_dir, "serverconfig.xml")):
            raise ActionError(f"A 7 Days to Die server folder for this key already exists ({server_dir}).")
        display = safe_name((spec.get("name") or key).strip()) or key
        seed = (spec.get("seed") or "").strip() or key
        if not re.match(r"^[A-Za-z0-9 _\-]{1,40}$", seed):
            raise ActionError("World seed: letters, digits, spaces, - and _ only (up to 40).")
        size = self.option(spec, "world_size")
        if size % 2048:
            raise ActionError("Random-world size must be 6144, 8192 or 10240.")
        xml = open(template, encoding="utf-8").read()
        values = {
            "ServerName": display,
            "ServerDescription": safe_name(spec.get("description") or "", 200),
            "ServerPassword": "set-at-launch",
            "ServerPort": ports["game"],
            "ServerVisibility": self.option(spec, "visibility"),
            "ServerMaxPlayerCount": self.option(spec, "maxplayers"),
            "GameWorld": self.option(spec, "world"),
            "WorldGenSeed": seed, "WorldGenSize": size,
            "GameName": re.sub(r"[^A-Za-z0-9_]", "_", key),
            "GameDifficulty": self.option(spec, "difficulty"),
            "EACEnabled": str(self.option(spec, "eac")).lower(),
            "TelnetEnabled": "true", "TelnetPort": ports["rcon"], "TelnetPassword": "set-at-launch",
            "WebDashboardEnabled": "false",     # its web panel would be one more thing exposed
            "UserDataFolder": os.path.join(server_dir, "data"),   # saves + generated worlds live here
        }
        for k, v in values.items():
            xml = self._set(xml, k, v)
        os.makedirs(os.path.join(server_dir, "data"), exist_ok=True)
        common.write_private(os.path.join(server_dir, "serverconfig.xml"), xml)   # will hold both passwords
        log = os.path.join(server_dir, "server.log")
        proc = f"-configfile={server_dir}/serverconfig.xml"
        run = os.path.join(install, f"worldcradle-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(secrets=config.secrets_path(), server_dir=server_dir,
                                         install=install, exe=EXE, log=log))
        os.chmod(run, 0o755)
        stop = os.path.join(install, f"worldcradle-{key}-stop.sh")
        with open(stop, "w", encoding="utf-8") as f:
            f.write(_STOP_TEMPLATE.format(secrets=config.secrets_path(), port=ports["rcon"], proc=proc))
        os.chmod(stop, 0o755)
        return {
            "exec_start": run, "exec_stop": stop, "working_dir": install,
            "game_port": ports["game"], "query_port": None, "rcon_port": ports["rcon"],
            "rcon_password_ref": "GAME_ADMIN_PASSWORD",
            "a2s": False, "proc_match": proc,
            "server_name": display, "join_port": ports["game"], "log_path": log,
            "install_dir": install, "steam_app": self.steam_app, "timeout_stop": 90,
            "world": key, "save_root": os.path.join(server_dir, "data"),
            "extra_ports": [ports["game"] + 1, ports["game"] + 2],
        }

    def _cmd(self, s, command: str, what: str) -> str:
        r = _telnet(s.rcon_port, s.rcon_password or "", command)
        if r is None:
            raise ActionError(f"{what} on {s.name} failed (the admin console didn't answer).")
        return r

    def probe(self, s) -> dict:
        out = empty_probe()
        r = _telnet(s.rcon_port, s.rcon_password or "", "lp") if s.rcon_port else None
        if r is not None:
            names = [m.group("name").strip() for m in _LP_ROW.finditer(r)]
            total = re.search(r"Total of (\d+) in the game", r)
            out.update(reachable=True, players=int(total.group(1)) if total else len(names),
                       player_names=names, player_detail=[{"name": n, "id": n} for n in names])
        try:
            cfg = open(os.path.join(os.path.dirname(s.save_root), "serverconfig.xml"), encoding="utf-8").read()
            m = re.search(r'name="ServerMaxPlayerCount"\s+value="(\d+)"', cfg)
            out["max_players"] = int(m.group(1)) if m else None
        except OSError:
            pass
        return out

    def valid_target(self, target: str) -> bool:
        return bool(re.match(r'^[^\r\n"\x00-\x1f]{1,64}$', target))

    def save(self, s) -> str:
        self._cmd(s, "saveworld", "Save")
        return "saved"

    def broadcast(self, s, message: str) -> str:
        self._cmd(s, 'say "' + message.replace('"', "'").replace("\n", " ")[:200] + '"', "Message")
        return "sent"

    def kick(self, s, target: str) -> str:
        self._cmd(s, f'kick "{target}"', "Kick")
        return "ok"

    def ban(self, s, target: str) -> str:
        self._cmd(s, f'ban add "{target}" 1 year', "Ban")
        return "ok"
