    label = "7 Days to Die"
    steam_app = 294420
    install_marker = EXE
    install_gb = 18
    ram_note = "about 6-12 GB of memory, more for large random worlds"
    about = "Zombie survival, crafting and base defence."
    actions = {"save", "broadcast", "kick", "ban"}

