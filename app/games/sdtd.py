"""7 Days to Die game type (native Linux dedicated server).

Settings are properties in the server's serverconfig.xml; each server gets a
copy of the file that ships with the installed version (so every default is
right for that version) with our values written in. Admin commands, the player
list and a clean shutdown go through the game's local "telnet" console.
"""
