"""Factorio game type (official headless server, native Linux).

Not a Steam download: Wube publishes the headless server as a free archive on
factorio.com. One shared install; each server has its own folder (map, mods,
settings). Setting names are keys of the game's server-settings.json. Players
and controls go through the game's RCON console.
"""
from __future__ import annotations

import io
import json
import os
import re
import tarfile
import urllib.request

import config
import monitor
from games.base import ActionError, GameType, opt_bool, opt_int, safe_name
from games.simple import RCON_PORT_HELP

DOWNLOAD_URL = "https://factorio.com/get-download/stable/headless/linux64"
RELEASES_URL = "https://factorio.com/api/latest-releases"
EXE = "bin/x64/factorio"
_NAME_RE = re.compile(r"^[A-Za-z0-9_.\-]{1,60}$")   # factorio.com usernames
_UA = {"User-Agent": "Mozilla/5.0 (GameDash)"}

_RUN_TEMPLATE = """#!/bin/sh
# gamedash-managed Factorio server — generated by provision().
# Settings: {server_dir}/server-settings.json     Map: {server_dir}/saves/world.zip
. {secrets}
# keep the join password in step with the ones set in GameDash
python3 - "{server_dir}/server-settings.json" "$GAME_SERVER_PASSWORD" <<'SYNC'
import json, sys
p = sys.argv[1]
d = json.load(open(p, encoding="utf-8"))
d["game_password"] = sys.argv[2]
json.dump(d, open(p, "w", encoding="utf-8"), indent=2)
SYNC
cd "{install}" || exit 1
# first start: create the map
[ -f "{server_dir}/saves/world.zip" ] || ./{exe} -c "{server_dir}/config.ini" --create "{server_dir}/saves/world.zip" || exit 1
exec ./{exe} -c "{server_dir}/config.ini" --start-server "{server_dir}/saves/world.zip" \\
    --server-settings "{server_dir}/server-settings.json" \\
    --server-adminlist "{server_dir}/server-adminlist.json" --port {gp} \\
    --rcon-bind 127.0.0.1:{rp} --rcon-password "$GAME_ADMIN_PASSWORD" \\
    --console-log "{log}"
"""


class FactorioGame(GameType):
    kind = "factorio"
    label = "Factorio"
    install_marker = EXE
    install_gb = 0.5
    ram_note = "about 1-4 GB of memory; grows with the size of the factory"
    about = "Factory building and automation. Light on resources."
    actions = {"save", "broadcast", "kick", "ban"}

    provisionable = True
    port_layout = [
        {"name": "game", "klass": "game", "start": 34197, "proto": "UDP", "forward": True,
         "label": "Game port (UDP)", "help": "The port players connect to. Forward it."},
        {"name": "rcon", "klass": "rcon", "start": 27070, "proto": "TCP", "label": "Admin console port (TCP)",
         "help": RCON_PORT_HELP},
    ]
    extra_fields = [
        {"name": "maxplayers", "label": "Max players (0 = no limit)", "type": "number", "min": 0,
         "max": 1000, "default": 0},
        {"name": "description", "label": "Description — optional", "placeholder": ""},
        {"name": "auto_pause", "label": "Pause the factory when nobody is online", "type": "checkbox",
         "default": True},
        {"name": "autosave_interval", "label": "Autosave every … minutes (1-120)", "type": "number",
         "min": 1, "max": 120, "default": 10},
        {"name": "verify_users", "label": "Only let in players signed in to a real factorio.com account",
         "type": "checkbox", "default": True},
        {"name": "admins", "label": "In-game admins — factorio.com usernames, comma-separated; optional",
         "placeholder": "yourname"},
    ]
    provision_hint = ("Factorio — a new map in its own folder, generated the first time the server "
                      "starts. The join password is the shared one. The server isn't listed in the "
                      "public browser (that needs a factorio.com login in its settings file); friends "
                      "use “Connect to address”.")

    def install(self, install_dir: str, on_progress=None) -> tuple[bool, str]:
        try:
            buf = io.BytesIO()
            req = urllib.request.Request(DOWNLOAD_URL, headers=_UA)   # the site refuses Python's default agent
            with urllib.request.urlopen(req, timeout=60) as r:
                total = int(r.headers.get("Content-Length") or 0)
                while True:
                    chunk = r.read(1 << 16)
                    if not chunk:
                        break
                    buf.write(chunk)
                    if on_progress and total:
                        on_progress("downloading", 100.0 * buf.tell() / total)
            buf.seek(0)
            os.makedirs(install_dir, exist_ok=True)
            with tarfile.open(fileobj=buf, mode="r:xz") as tf:   # archive root is "factorio/": strip it
                members = []
                for m in tf.getmembers():
                    parts = m.name.split("/", 1)
                    if len(parts) < 2 or parts[0] != "factorio":
                        continue
                    m.name = parts[1]
                    members.append(m)
                tf.extractall(install_dir, members=members, filter="data")
            try:
                with urllib.request.urlopen(urllib.request.Request(RELEASES_URL, headers=_UA), timeout=15) as r:
                    version = json.load(r)["stable"]["headless"]
            except Exception:
                version = "stable"
            with open(os.path.join(install_dir, "version.txt"), "w", encoding="utf-8") as f:
                f.write(version + "\n")
            return True, f"Factorio {version}"
        except Exception as e:
            return False, f"couldn't download the Factorio server from factorio.com: {e}"

    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        if not os.path.isfile(os.path.join(install, EXE)):
            raise ActionError(f"Factorio isn't installed ({install}).")
        key = spec["key"]
        server_dir = os.path.join(install, "gamedash-servers", key)
        if os.path.exists(os.path.join(server_dir, "server-settings.json")):
            raise ActionError(f"A Factorio server folder for this key already exists ({server_dir}).")
        display = safe_name((spec.get("name") or key).strip()) or key
        admins = [a.strip() for a in (spec.get("admins") or "").split(",") if a.strip()]
        bad = [a for a in admins if not _NAME_RE.match(a)]
        if bad:
            raise ActionError(f"Not a valid factorio.com username: {bad[0]}")
        settings = {
            "name": display,
            "description": safe_name(spec.get("description") or "", 200),
            "tags": [],
            "max_players": opt_int(spec, "maxplayers", 0, 0, 1000, "Max players"),
            "visibility": {"public": False, "lan": True},
            "username": "", "password": "", "token": "",
            "game_password": "set-at-launch",
            "require_user_verification": opt_bool(spec, "verify_users", True),
            "auto_pause": opt_bool(spec, "auto_pause", True),
            "autosave_interval": opt_int(spec, "autosave_interval", 10, 1, 120, "Autosave interval"),
            "autosave_slots": 5,
        }
        os.makedirs(os.path.join(server_dir, "saves"), exist_ok=True)
        fd = os.open(os.path.join(server_dir, "server-settings.json"),
                     os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)   # will hold the join password
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            json.dump(settings, f, indent=2)
        # in-game admins are their own file, not a server-settings.json entry
        with open(os.path.join(server_dir, "server-adminlist.json"), "w", encoding="utf-8") as f:
            json.dump(admins, f)
        with open(os.path.join(server_dir, "config.ini"), "w", encoding="utf-8") as f:
            # game files are read from the shared install; everything written stays in this folder
            f.write("[path]\nread-data=__PATH__executable__/../../data\n"
                    f"write-data={server_dir}\n")
        log = os.path.join(server_dir, "console.log")
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(secrets=config.secrets_path(), server_dir=server_dir,
                                         install=install, exe=EXE, gp=ports["game"],
                                         rp=ports["rcon"], log=log))
        os.chmod(run, 0o755)
        return {
            "exec_start": run, "working_dir": install,
            "game_port": ports["game"], "query_port": None, "rcon_port": ports["rcon"],
            "rcon_password_ref": "GAME_ADMIN_PASSWORD",
            "a2s": False, "proc_match": f"-c {server_dir}/config.ini",
            "server_name": display, "join_port": ports["game"], "log_path": log,
            "install_dir": install,
            # the stop signal makes the server save the map and quit
            "kill_signal": "SIGINT", "timeout_stop": 60,
            "world": key, "save_root": server_dir,
        }

    def _rcon(self, s, cmd: str) -> str | None:
        return monitor.rcon_run(s.rcon_port, s.rcon_password, cmd)

    @staticmethod
    def parse_players(text: str) -> list[str] | None:
        # "Online players (2):\n  alice (online)\n  bob (online)\n"
        if not re.search(r"Online players \(\d+\)", text or ""):
            return None
        return [m.group(1) for m in re.finditer(r"(?m)^\s+(\S+) \(online\)\s*$", text)]

    def probe(self, s) -> dict:
        out = {"players": None, "player_names": [], "player_detail": [],
               "max_players": None, "reachable": None}
        names = self.parse_players(self._rcon(s, "/players online") or "") if s.rcon_port else None
        if names is not None:
            out.update(reachable=True, players=len(names), player_names=names,
                       player_detail=[{"name": n, "id": n} for n in names])
        try:
            limit = json.load(open(os.path.join(s.save_root, "server-settings.json"),
                                   encoding="utf-8")).get("max_players")
            out["max_players"] = limit or None   # 0 = unlimited
        except (OSError, ValueError):
            pass
        return out

    def valid_target(self, target: str) -> bool:
        return bool(_NAME_RE.match(target))

    def _do(self, s, cmd: str, what: str) -> str:
        r = self._rcon(s, cmd)
        if r is None:
            raise ActionError(f"{what} on {s.name} failed (the admin console didn't answer).")
        return r.strip() or "ok"

    def save(self, s) -> str:
        self._do(s, "/server-save", "Save")
        return "saved"

    def broadcast(self, s, message: str) -> str:
        # plain text on the console is said to everyone as the server
        self._do(s, message.replace("\n", " ").lstrip("/")[:200], "Message")
        return "sent"

    def kick(self, s, target: str) -> str:
        return self._do(s, f"/kick {target}", "Kick")

    def ban(self, s, target: str) -> str:
        return self._do(s, f"/ban {target}", "Ban")
