"""Barotrauma game type (native Linux dedicated server).

The server keeps its settings next to its own program files, so each server
gets its own copy of the (small) install. Name, ports, limit and password are
launch arguments. Who is online is read from the server's output.
"""
from __future__ import annotations

import os
import re

import config
import monitor
from games.base import ActionError, GameType, opt_bool, opt_int, safe_name

EXE = "DedicatedServer"
_EVENTS = re.compile(r"^\s*(?P<joined>[^\r\n]{1,40}?) has joined the server\.\s*$|^\s*(?P<left>[^\r\n]{1,40}?) has left the server\.\s*$", re.M)

_RUN_TEMPLATE = """#!/bin/sh
# gamedash-managed Barotrauma server — generated by provision().
# This server's own copy of the game (and its serversettings.xml): {install}
. {secrets}
cd "{install}" || exit 1
exec ./{exe} -name "{name}" -port {gp} -queryport {qp} -maxplayers {maxp} \\
    -public {public} -password "$GAME_SERVER_PASSWORD" > "{log}" 2>&1 < /dev/null
"""


class BarotraumaGame(GameType):
    kind = "barotrauma"
    label = "Barotrauma"
    steam_app = 1026340
    install_marker = EXE
    install_gb = 0.4
    ram_note = "about 1-2 GB of memory"
    about = "Co-op submarine survival in an alien ocean. Light on resources."
    actions: set[str] = set()

    provisionable = True
    needs_install_clone = True
    base_port = 27600
    port_layout = [
        {"name": "game", "klass": "game", "start": 27600, "proto": "UDP", "forward": True,
         "label": "Game port (UDP)", "help": "The port players connect to. Forward it (UDP)."},
        {"name": "query", "klass": "query", "start": 27601, "proto": "UDP", "forward": True,
         "label": "Steam query port (UDP)", "help": "Used when the server is listed publicly. Forward it (UDP)."},
    ]
    extra_fields = [
        {"name": "maxplayers", "label": "Max players (1-16)", "type": "number", "min": 1, "max": 16,
         "default": 8},
        {"name": "public", "label": "List in the public server browser", "type": "checkbox",
         "default": False},
    ]
    provision_note = ("Barotrauma keeps its settings beside its program files, so each server gets its "
                      "own copy of the game (under half a GB).")
    provision_hint = ("Barotrauma — a new server with its own copy of the game. The join password is the "
                      "shared one. Round settings (submarine, mission, difficulty) are chosen in the "
                      "game's lobby by whoever has permission.")

    def provision(self, spec: dict, ports: dict) -> dict:
        install = spec.get("install_dir") or config.install_dir(self.kind)
        if not os.path.isfile(os.path.join(install, EXE)):
            raise ActionError(f"Barotrauma install missing: {install}")
        key = spec["key"]
        display = safe_name((spec.get("name") or key).strip()) or key
        log = os.path.join(install, "gamedash-console.log")
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(
                secrets=config.secrets_path(), install=install, exe=EXE, name=display,
                gp=ports["game"], qp=ports["query"], log=log,
                maxp=opt_int(spec, "maxplayers", 8, 1, 16, "Max players"),
                public="true" if opt_bool(spec, "public", False) else "false"))
        os.chmod(run, 0o755)
        return {
            "exec_start": run, "working_dir": install,
            "game_port": ports["game"], "query_port": ports["query"], "rcon_port": None,
            "a2s": False, "proc_match": f"-port {ports['game']} -queryport",
            "server_name": display, "join_port": ports["game"], "log_path": log,
            "install_dir": install, "steam_app": self.steam_app, "timeout_stop": 30,
            "world": key,
            "save_root": os.path.expanduser("~/.local/share/Daedalic Entertainment GmbH/Barotrauma/Multiplayer"),
        }

    def save_paths(self, s) -> list[dict]:
        return [{"path": s.save_root, "role": "save"}] if s.save_root else []

    def probe(self, s) -> dict:
        out = {"players": None, "player_names": [], "player_detail": [],
               "max_players": None, "reachable": None}
        names = monitor.roster_from_log(s.log_path, _EVENTS) if s.log_path else None
        if names is not None:
            out.update(players=len(names), player_names=names,
                       player_detail=[{"name": n, "id": ""} for n in names])
        return out
