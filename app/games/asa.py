"""ARK: Survival Ascended game type. Windows-only server, run under Wine.

Works like ARK: Survival Evolved (same RCON console, same launch-line style),
so the player list and the save / message / kick / ban controls are inherited
from that game type. Each map is a server with its own save folder; maps with
the same cluster name share characters.
"""
from __future__ import annotations

import os
import re
import sys

import config
from games import common
from games.ark import GAMEDASH_DIR, ArkGame
from games.base import ActionError, GameType, opt_bool, opt_choice, opt_int, safe_name
from games.simple import RCON_PORT_HELP

EXE = "ShooterGame/Binaries/Win64/ArkAscendedServer.exe"
MAPS = [["TheIsland_WP", "The Island"], ["ScorchedEarth_WP", "Scorched Earth"],
        ["TheCenter_WP", "The Center"], ["Aberration_WP", "Aberration"],
        ["Extinction_WP", "Extinction"], ["Astraeos_WP", "Astraeos"], ["Ragnarok_WP", "Ragnarok"]]

_RUN_TEMPLATE = """#!/bin/sh
# gamedash-managed ARK: Survival Ascended map — generated by provision().
. {secrets}
mkdir -p "{cluster_dir}"
{wine}cd "{install}/ShooterGame/Binaries/Win64" || exit 1
exec wine ./ArkAscendedServer.exe \\
    "{opts}" \\
    -port={gp} -WinLiveMaxPlayers={maxp} -NoBattlEye -server -log \\
    -clusterid={cluster_id} -ClusterDirOverride="{cluster_dir_win}"{flags}
"""


class AsaGame(ArkGame):
    join_steps = GameType.join_steps     # not ARK's Steam-favourites route
    kind = "asa"
    label = "ARK Ascended"
    title = "ARK: Survival Ascended"
    steam_app = 2430930
    steam_platform = "windows"
    requires = ["wine"]
    update_script = None
    install_marker = EXE
    install_gb = 16
    ram_note = "about 12-16 GB of memory per running map"
    about = "The remake of ARK. Very heavy; the server is Windows-only, so it runs through Wine."

    port_layout = [
        {"name": "game", "klass": "game", "start": 7800, "proto": "UDP", "forward": True,
         "label": "Game port (UDP)", "help": "The port players connect to. Forward it (UDP)."},
        {"name": "rcon", "klass": "rcon", "start": 27045, "proto": "TCP", "label": "Admin console port (TCP)",
         "help": RCON_PORT_HELP},
    ]
    provision_hint = ("ARK: Survival Ascended — adds a map (a Windows server, run through Wine). The join "
                      "and admin passwords are the shared ones; maps with the same cluster name share "
                      "characters and dinos. BattlEye anti-cheat is off because it can't run under "
                      "Wine. Each running map needs a lot of memory, and the first start takes 5-10 "
                      "minutes.")

    @property
    def extra_fields(self) -> list[dict]:
        return [
            {"name": "map", "label": "Map", "type": "select", "options": MAPS, "default": "TheIsland_WP"},
            {"name": "maxplayers", "label": "Max players (1-127)", "type": "number", "min": 1,
             "max": 127, "default": 10},
            {"name": "mode", "label": "Game mode", "type": "select",
             "options": [["pve", "PvE"], ["pvp", "PvP"]], "default": "pve"},
            {"name": "mods", "label": "Mod IDs — optional, comma-separated CurseForge project IDs",
             "placeholder": "928793,900062"},
            {"name": "crossplay", "label": "Allow console players (crossplay)", "type": "checkbox",
             "default": False},
            {"name": "cluster_id", "label": "Cluster name (blank = the configured default)",
             "placeholder": "gamedash"},
        ]

    def provision(self, spec: dict, ports: dict) -> dict:
        install = config.install_dir(self.kind)
        if not os.path.isfile(os.path.join(install, EXE)):
            raise ActionError(f"ARK: Survival Ascended isn't installed ({install}).")
        cfg = config.load()
        cluster_id = (spec.get("cluster_id") or "").strip() or cfg.get("ark_cluster_id") or "gamedash"
        if not re.match(r"^[A-Za-z0-9_]{1,40}$", cluster_id):
            raise ActionError("Cluster name must be letters/digits/underscores.")
        key = spec["key"]
        mapcode = opt_choice(spec, "map", [m for m, _ in MAPS], "TheIsland_WP", "Map")
        display = safe_name((spec.get("name") or mapcode).strip()) or mapcode
        maxp = opt_int(spec, "maxplayers", 10, 1, 127, "Max players")
        pve = opt_choice(spec, "mode", ("pve", "pvp"), "pve", "Game mode") == "pve"
        mods = "".join((spec.get("mods") or "").split())
        if mods and not re.match(r"^\d{3,12}(,\d{3,12})*$", mods):
            raise ActionError("Mod IDs must be numbers separated by commas.")
        gp, rp = ports["game"], ports["rcon"]
        save = "gd_" + key.replace("-", "_")
        cluster_dir = os.path.join(install, "cluster")
        # The admin password must be the LAST "?" option: this game reads everything after it
        # as part of the password. The port is given both ways: without ?Port= it also opens 7777.
        opts = (f"{mapcode}?listen?SessionName={display}"
                f"?Port={gp}?RCONEnabled=True?RCONPort={rp}?AltSaveDirectoryName={save}"
                f"?ServerPVE={'True' if pve else 'False'}"
                "?ServerPassword=${GAME_SERVER_PASSWORD}?ServerAdminPassword=${GAME_ADMIN_PASSWORD}")
        # with no -ServerPlatform the game lets every platform in, so "off" has to say PC only
        flags = (f" -mods={mods}" if mods else "") + \
                (" -ServerPlatform=ALL" if opt_bool(spec, "crossplay", False) else " -ServerPlatform=PC")
        run = os.path.join(install, f"gamedash-{key}-run.sh")
        with open(run, "w", encoding="utf-8") as f:
            f.write(_RUN_TEMPLATE.format(
                secrets=config.secrets_path(), install=install, opts=opts, maxp=maxp,
                cluster_id=cluster_id, cluster_dir=cluster_dir, flags=flags, gp=gp,
                cluster_dir_win="Z:" + cluster_dir.replace("/", "\\\\"),
                wine=common.wine_env_lines(common.wine_prefix(self.kind, key))))
        os.chmod(run, 0o755)
        stop = os.path.join(install, f"gamedash-{key}-stop.sh")   # RCON SaveWorld + DoExit
        with open(stop, "w", encoding="utf-8") as f:
            f.write("#!/bin/sh\n"
                    f". {config.secrets_path()}\n"
                    f'"{sys.executable}" "{os.path.join(GAMEDASH_DIR, "arkstop.py")}" {rp} "$GAME_ADMIN_PASSWORD"\n'
                    # The world is saved before the exit command returns. The game then takes about
                    # 40 s to close and Wine's helper programs linger after it, so give it 45 s and
                    # then close that Wine environment, keeping the stop well inside its time limit.
                    f"i=0\nwhile [ $i -lt 45 ] && pgrep -f -- 'AltSaveDirectoryName={save}' >/dev/null; "
                    "do sleep 1; i=$((i+1)); done\n"
                    f'WINEPREFIX="{common.wine_prefix(self.kind, key)}" wineserver -k 2>/dev/null\n'
                    "exit 0\n")
        os.chmod(stop, 0o755)
        return {
            "exec_start": run, "exec_stop": stop, "working_dir": install,
            "game_port": gp, "query_port": None, "rcon_port": rp,
            "rcon_password_ref": "GAME_ADMIN_PASSWORD",
            "a2s": False, "proc_match": f"AltSaveDirectoryName={save}?",
            "server_name": display, "join_port": gp,
            "install_dir": install, "steam_app": self.steam_app,
            "timeout_stop": 130, "save_dir": save, "cluster_id": cluster_id,
        }
