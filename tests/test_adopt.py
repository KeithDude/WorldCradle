"""Adopting an existing server onto its game's standard launch: new scripts, service file and
record — its settings files, world and saves untouched, and everything replaced kept."""
import glob
import os

import pytest

import provision
import store
from games.base import ActionError


@pytest.fixture
def palworld(tmp_path, monkeypatch):
    install = tmp_path / "palworldserver"
    (install / "Pal/Saved/Config/LinuxServer").mkdir(parents=True)
    (install / "PalServer.sh").write_text("#!/bin/sh\n")
    ini = install / "Pal/Saved/Config/LinuxServer/PalWorldSettings.ini"
    ini.write_text('OptionSettings=(ServerName="Dudeworld",bIsPvP=True,ExpRate=2.000000)\n')
    (install / "realmcradle-pw-run.sh").write_text("#!/bin/sh\n# the hand-made launch\n")
    units = tmp_path / "units"
    units.mkdir()
    (units / "realmcradle-pw.service").write_text("[Service]\nExecStart=old\n")
    monkeypatch.setattr(provision, "SYSTEMD_DIR", str(units))
    monkeypatch.setattr(store, "STORE_PATH", str(tmp_path / "servers.json"))
    store.save([{"key": "pw", "kind": "palworld", "name": "Palworld · Dudeworld", "managed": "realmcradle",
                 "unit": "realmcradle-pw.service", "install_dir": str(install), "server_name": "Dudeworld",
                 "game_port": 8211, "query_port": 27018, "rcon_port": 25575, "proc_match": "PalServer-Linux",
                 "backup_keep": 9, "slot_group": "old-idea"}])
    running = set()
    monkeypatch.setattr(provision.systemd, "is_active", lambda unit: unit in running)
    monkeypatch.setattr(provision.systemd, "check", lambda *a, **kw: None)
    return install, ini, units, running


def _adopt():
    return provision.adopt("pw", {"maxplayers": 10}, {"game": 8211, "query": 27018, "rcon": 25575})


def test_adopting_makes_the_standard_launch_and_keeps_what_it_replaced(palworld):
    install, ini, units, _ = palworld
    settings_before = ini.read_text()
    r = _adopt()
    run = (install / "realmcradle-pw-run.sh").read_text()
    assert "-port=8211 -queryport=27018" in run and "generated by provision()" in run
    assert (install / "realmcradle-pw-stop.sh").is_file()
    assert "ExecStop=" in (units / "realmcradle-pw.service").read_text()
    assert ini.read_text() == settings_before            # its settings are not rewritten
    kept = glob.glob(str(install / "realmcradle-pw-run.sh.before-adopt-*"))
    assert kept and "hand-made" in open(kept[0]).read()
    assert len(r["kept"]) == 3                           # run script, service file, server list
    entry = store.get("pw")
    assert entry["proc_match"] == "-port=8211 " and entry["server_name"] == "Dudeworld"
    assert entry["backup_keep"] == 9 and "slot_group" not in entry
    assert entry["name"] == "Palworld · Dudeworld"


def test_a_running_server_is_not_adopted(palworld):
    *_, running = palworld
    running.add("realmcradle-pw.service")
    with pytest.raises(ActionError, match="Stop"):
        _adopt()
    assert "hand-made" in open(os.path.join(palworld[0], "realmcradle-pw-run.sh")).read()
